export type Locale = "en" | "ru";
export function translator(locale: Locale) {
  const i = new I18N();
  i.registerKeysets("en", { app: dictionaries.en });
  i.registerKeysets("ru", { app: dictionaries.ru });
  i.setLang(locale);
  return (key: string) =>
    Object.hasOwn(dictionaries.en, key)
      ? i.i18n("app", key)
      : i.i18n("app", "error");
}
